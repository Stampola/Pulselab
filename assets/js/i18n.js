const I18nManager = {
  current: 'th',

  init() {
    this.current = localStorage.getItem('liftora_lang') || 'th';
    this.apply();
    document.querySelectorAll('[data-action="toggle-lang"]').forEach(btn => {
      btn.addEventListener('click', () => this.toggle());
      btn.textContent = this.current === 'th' ? 'EN' : 'TH';
    });
  },

  apply() {
    document.documentElement.lang = this.current;
    const dict = I18N[this.current];
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) el.textContent = dict[key];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) el.setAttribute('placeholder', dict[key]);
    });
    document.querySelectorAll('[data-action="toggle-lang"]').forEach(btn => {
      btn.textContent = this.current === 'th' ? 'EN' : 'TH';
    });
  },

  toggle() {
    this.current = this.current === 'th' ? 'en' : 'th';
    localStorage.setItem('liftora_lang', this.current);
    this.apply();
  },

  t(key) {
    return I18N[this.current][key] || key;
  }
};

document.addEventListener('DOMContentLoaded', () => I18nManager.init());
